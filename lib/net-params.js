'use strict';
/**
 * 网络参数 —— 双端同构的唯一声明处
 * ================================
 *
 * 为什么单独一个文件，而不放进 lib/config.js
 * ------------------------------------------
 * lib/config.js 是**凭据入口**，被构建脚本有意排除在浏览器产物之外：
 *   · build-static.js 的 MODULES 里没有它；
 *   · 浏览器侧一旦引用 config 模块，「模块引用闸门」会直接报错；
 *   · lib/source.js 里对 cfg 的引用整个包在 @node-only 区块内，打包时被剥离。
 * 而 lib/source.js 是 Node / 浏览器双端同构模块，它的超时参数在两端都要生效。
 * 所以超时参数**不能**放 config.js —— 放进去在浏览器侧会拿不到值。
 *
 * 因此本文件的硬约束：
 *   1. 不得 require 任何 Node 内置模块（fs / https / zlib 等）；
 *   2. 不得在运行时读取环境变量（浏览器侧没有这一层）；
 *   3. 只能包含纯字面量常量。
 * 违反任意一条都会让静态产物在浏览器里崩掉，而构建期的模块引用闸门未必拦得住。
 *
 * ⚠️ 书写注意：本文件的注释会被原样打进 docs/bundle.js，而构建后的密钥扫描
 *    会在产物里匹配敏感字面量。所以这里**不要**把敏感 API 名字原样写进注释 ——
 *    扫描器不区分注释与代码，命中即中止构建。用中文描述代替字面量。
 *
 * 之前的问题：这些值以裸字面量的形式散落在 source.js 的多个函数签名里
 * （9000 出现 6 次、6000 出现 3 次）。改一处漏几处 → 不同数据源超时彼此不一致，
 * 且没有任何报错。现在收敛到此处，由 scripts/verify-no-shadow-config.js
 * 断言消费侧不再出现裸字面量。
 */
module.exports = {
  /** 普通行情接口超时（腾讯 / 新浪 JSONP） */
  API_TIMEOUT_MS: 9000,
  /** 快速失败型短超时：东方财富（仅 Node 可达）与搜索联想接口。
   *  这两类请求失败后都有备选路径，不必长时间等待。 */
  FAST_TIMEOUT_MS: 6000,
  /** 搜索联想：输入即触发，对延迟最敏感，超时需明显短于普通行情 */
  SUGGEST_TIMEOUT_MS: 4000,
  /** 重定向跟随上限 */
  MAX_REDIRECTS: 3,
};
